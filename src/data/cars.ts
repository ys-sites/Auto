export interface Car {
  id: string;
  make: string;
  model: string;
  year: number;
  price: number;
  // Sale pricing: originalPrice is the struck-through anchor; price is what the buyer pays.
  // When set and > price, cards + VDP show "was X, now Y" with a -% pill to drive urgency.
  originalPrice?: number;
  // Mileage is optional: FB Marketplace listings don't publish it.
  // The VDP hides the mileage block when absent — never invent a number.
  mileage?: number;
  type: 'SUV' | 'Sedan' | 'Coupe' | 'Convertible' | 'Minivan' | 'Hatchback' | 'Wagon';
  fuel: 'Petrol' | 'Diesel' | 'Electric' | 'Hybrid';
  transmission: 'Automatic' | 'Manual';
  image: string;
  // Full photo set for the VDP gallery. When present, the gallery shows
  // all photos with thumbnails; `image` stays the card/OG primary.
  images?: string[];
  description: string;
  descriptionFr?: string;
  features: string[];
  // Availability: sold cars stay listed with a SOLD overlay (SEO + social proof)
  status: 'available' | 'sold';
  badge?: string;      // e.g. "Just flipped"
  badgeFr?: string;
  // "What we fixed" — the flip story. Displayed as a checklist on the VDP.
  reconditioning: string[];
  reconditioningFr?: string[];
}

